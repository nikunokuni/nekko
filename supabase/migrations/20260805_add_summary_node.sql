-- ノードに「まとめ」を持たせる（束ねの境界＋戦型全体の考え方）
--
--   ねらいは2つ：
--     ① 子ノードが増えてマップが見にくくなったとき、マップ上で束ねられるようにする
--     ② 局面ではなく戦型そのものに対する考え方（棋書の章末まとめ）を書く場所を作る
--
--   「主根／側根」という2種類のノードに分ける案もあったが、is_inbox のときと
--   同じ判断で見送った（20260802_add_inbox_node.sql 参照）。ツリー構造を増やすと
--   rootId 前提で組まれたレイアウト・コピー・公開まわりに影響が波及する。
--   さらに型を2つ持つと「型ごとに項目を出し分ける」ことになり、型を切り替えた
--   瞬間に入力済みの値が画面から消える（＝静かに見えなくなる）事故が起きる。
--   目印のフラグ1つと本文1つで足りるため、普通のノードのまま印だけを足す。
--
--   ・is_summary … このノードから下を束ねられる（＝章の見出し）
--   ・summary    … 戦型全体の考え方・指針。局面に紐づく aim/caution/next_study とは別物。
--                  「まとめだけを続けて読む」ために列を分けてある
--
--   既定値は false / '' なので、既存ツリーの見た目も挙動も変わらない。
--   畳んだ／開いたの状態はDBに持たない（端末ローカルの表示状態にすぎず、
--   ここへ書くと nodes の更新トリガーで trees.updated_at が動いてしまい、
--   「畳んだだけ」でツリー一覧の更新日と並び順が変わる。
--   20260714_touch_tree_updated_at.sql 参照）。
--
--   copy_tree は列名を並べない書き方に変えてあるので触る必要はない
--   （20260803_copy_tree_without_column_list.sql）。
-- Supabase の SQL Editor で実行してください
-- ══════════════════════════════════════════════════════════════════

alter table public.nodes
  add column if not exists is_summary boolean not null default false,
  add column if not exists summary    text    not null default '';
