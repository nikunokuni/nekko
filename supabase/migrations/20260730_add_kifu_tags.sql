-- 棋譜（kifus）に戦法タグを追加
--   ノードの「相手の戦法 / 自分の戦法」と同じ戦法タグを棋譜にも付けられる
--   ようにする。ノード編集画面の棋譜ピッカーで、そのノードのタグと一致する
--   棋譜を上位に並べるために使う。
--   形式は nodes.tags と同じ jsonb の文字列配列。
-- Supabase の SQL Editor で実行してください
-- ══════════════════════════════════════════════════

alter table public.kifus
  add column if not exists tags jsonb not null default '[]'::jsonb;
