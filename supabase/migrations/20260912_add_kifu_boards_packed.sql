-- 局面検索用に、盤面を詰めた文字列の置き場を足す
--
--   kifus.snapshots（JSON）は1局面464バイトあり、300局で約16MB になる。
--   「保存した棋譜の中から、この形が出た局面を探す」には全局面を見る必要があるが、
--   検索のたびに16MBを読むことはできない。
--
--   そこで1マス1文字に詰めた文字列（1局面81文字）を別に持つ。約1/5.7になるので、
--   300局でも3MB弱に収まり、検索を始めるときに一度読めばあとは端末の中だけで探せる。
--   詰め方は src/kifuPosition.js が持つ（コードの唯一の出どころ）。
--
--   snapshots と同じ中身を二重に持つことになるが、
--     ・DB容量は300局で+3MB程度（無料プランの500MBに対して誤差）
--     ・snapshots 側は再生に、こちらは検索に使う。どちらも消せない
--   なので重複を受け入れる。作るのは取り込み時（src/db.js の createKifu）で、
--   この列より前に保存した棋譜は null のまま入るため、検索画面が後から埋める。
--
-- Supabase の SQL Editor で実行してください
-- ══════════════════════════════════════════════════

alter table public.kifus
  add column if not exists boards_packed text;

comment on column public.kifus.boards_packed is
  '局面検索用。1局面81文字（1マス1文字）を手数ぶん連結したもの。作り方は src/kifuPosition.js';
