-- 棋譜に「しおり」を持たせる（分岐にしたい手の印）
--
--   棋譜からツリーを作る作業は2段階になる。
--     ① 棋譜を通して見て、分岐にしたい手を全部見つける（読む作業）
--     ② 1つずつノードにまとめる（書く作業）
--   分けること自体は正しいが、①で見つけた場所がどこにも残らないため、
--   ②を始めるときにまた探すところからやり直しになっていた。
--
--   ・bookmarks … [{ ply, done }] の配列。ply は手数（0 = 初期局面）。
--                 done は「この手からノードを作った」印。
--
--   **ノードにしても、しおりは消さずに done を立てるだけにする。**
--   消すと「自分がどのあたりを分岐点だと思ったか」の記録がその場で失われる。
--   これは機械が数えられる事実（利用者が付けた印）なので、あとから
--   「何手目に分岐しがちか」「そのときの局面の特徴は何か」を集計できる。
--   アプリが「ここが分岐点だ」と言うのではなく、付いた印を数えるだけ、という
--   線引きは kifuBranching.js と同じ（事実は機械、理由は人間）。
--
--   軽い列なので一覧でも読む（KIFU_META_COLUMNS に載る）。
--   棋譜ライブラリの一覧から「しおりが残っている棋譜」を見つけられないと、
--   ①と②のあいだで作業の続きが行方不明になり、機能の意味が無くなる。
--
--   既定値は空配列なので、既存の棋譜の見た目も挙動も変わらない。
-- Supabase の SQL Editor で実行してください
-- ══════════════════════════════════════════════════════════════════

alter table public.kifus
  add column if not exists bookmarks jsonb not null default '[]'::jsonb;
